/**
 * DDL preview generated from the app definition (requirements §3.4: "DDL view per dialect").
 * SQL types start from FIELD_TYPES (written in PostgreSQL) and are translated per dialect.
 * Mongo shows the collection's $jsonSchema validator; Redis shows the key pattern and TTL.
 */
import {
  FIELD_TYPES,
  snake,
  type DbConnection,
  type DbEngine,
  type Table,
  type TableField,
  type TableFieldType,
} from '@platon/definition'

export type SqlDialect = 'postgres' | 'mysql' | 'mssql'
export const SQL_DIALECTS: SqlDialect[] = ['postgres', 'mysql', 'mssql']
const DIALECT_LABEL: Record<SqlDialect, string> = {
  postgres: 'PostgreSQL',
  mysql: 'MySQL',
  mssql: 'SQL Server',
}

export function isSqlEngine(e: DbEngine): e is SqlDialect {
  return e === 'postgres' || e === 'mysql' || e === 'mssql'
}

const TRANSLATE: Record<string, Record<Exclude<SqlDialect, 'postgres'>, string>> = {
  BIGSERIAL: { mysql: 'BIGINT', mssql: 'BIGINT' },
  BIGINT: { mysql: 'BIGINT', mssql: 'BIGINT' },
  'VARCHAR(255)': { mysql: 'VARCHAR(255)', mssql: 'NVARCHAR(255)' },
  'VARCHAR(64)': { mysql: 'VARCHAR(64)', mssql: 'NVARCHAR(64)' },
  TEXT: { mysql: 'TEXT', mssql: 'NVARCHAR(MAX)' },
  'TEXT[]': { mysql: 'JSON', mssql: 'NVARCHAR(MAX)' },
  'NUMERIC(12,2)': { mysql: 'DECIMAL(12,2)', mssql: 'DECIMAL(12,2)' },
  DATE: { mysql: 'DATE', mssql: 'DATE' },
  TIMESTAMPTZ: { mysql: 'DATETIME', mssql: 'DATETIMEOFFSET' },
  BOOLEAN: { mysql: 'TINYINT(1)', mssql: 'BIT' },
  UUID: { mysql: 'CHAR(36)', mssql: 'UNIQUEIDENTIFIER' },
  JSONB: { mysql: 'JSON', mssql: 'NVARCHAR(MAX)' },
}

export function sqlType(type: TableFieldType, d: SqlDialect): string {
  const pg = FIELD_TYPES[type].sql
  return d === 'postgres' ? pg : (TRANSLATE[pg]?.[d] ?? pg)
}

/** Physical column: link fields store the target's id. */
export function columnName(f: Pick<TableField, 'key' | 'type'>): string {
  const c = snake(f.key) || f.key
  return f.type === 'link' ? `${c}_id` : c
}

/** Table name without schema / key pattern. */
export function tableName(t: Pick<Table, 'id' | 'physicalName'>): string {
  const p = t.physicalName?.split('.').pop()
  return p && !p.includes(':') ? p : t.id
}

const RESERVED = new Set([
  'order',
  'group',
  'user',
  'select',
  'from',
  'where',
  'table',
  'key',
  'desc',
  'asc',
  'limit',
  'check',
  'default',
  'index',
  'primary',
  'references',
  'column',
  'to',
  'end',
  'value',
])

export function quote(name: string, d: SqlDialect): string {
  if (d === 'mysql') return `\`${name}\``
  if (d === 'mssql') return `[${name}]`
  return RESERVED.has(name.toLowerCase()) || !/^[a-z_][a-z0-9_]*$/.test(name) ? `"${name}"` : name
}

export interface DdlContext {
  connection: DbConnection
  /** All tables of the app, to resolve link targets. */
  tables: Table[]
  /** Allowed values for workflow_state fields. */
  workflowStates?: (workflowId: string) => string[]
  /** Indexes & comments. */
  extras?: boolean
}

const sqlStr = (s: string) => `'${s.replace(/'/g, "''")}'`

export function generateSqlDdl(table: Table, ctx: DdlContext, d: SqlDialect): string {
  const { connection: conn, extras } = ctx
  const schema =
    d === 'mysql'
      ? ''
      : d === 'mssql'
        ? conn.engine === 'mssql'
          ? (conn.schema ?? 'dbo')
          : 'dbo'
        : conn.engine === 'postgres'
          ? (conn.schema ?? 'public')
          : 'public'
  const full = (n: string) => (schema ? `${quote(schema, d)}.` : '') + quote(n, d)
  const tn = tableName(table)
  const out: string[] = [
    `-- ${conn.name} · ${DIALECT_LABEL[d]}`,
    `-- Generated by Platon Studio from data.tables.${table.id}`,
    '',
  ]
  const cols: string[] = []
  cols.push(
    d === 'postgres'
      ? `  ${quote('id', d)} BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY`
      : d === 'mysql'
        ? `  ${quote('id', d)} BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY`
        : `  ${quote('id', d)} BIGINT IDENTITY(1,1) PRIMARY KEY`,
  )
  for (const f of table.fields) {
    const c = quote(columnName(f), d)
    let line = `  ${c} ${sqlType(f.type, d)}`
    if (f.type === 'auto_number') line += d === 'postgres' ? ' UNIQUE' : ' NOT NULL UNIQUE'
    else {
      if (f.req) line += ' NOT NULL'
      if (f.unique) line += ' UNIQUE'
    }
    if (f.type === 'link') {
      const target = ctx.tables.find((t) => t.id === f.link)
      if (target && target.connection === table.connection)
        line += ` REFERENCES ${full(tableName(target))} (${quote('id', d)})`
    }
    const allowed =
      f.type === 'single_select'
        ? f.options
        : f.type === 'workflow_state' && f.workflow
          ? ctx.workflowStates?.(f.workflow)
          : undefined
    if (allowed?.length) line += `\n    CHECK (${c} IN (${allowed.map(sqlStr).join(', ')}))`
    cols.push(line)
  }
  cols.push(
    d === 'postgres'
      ? `  ${quote('created_at', d)} TIMESTAMPTZ NOT NULL DEFAULT now()`
      : d === 'mysql'
        ? `  ${quote('created_at', d)} DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP`
        : `  ${quote('created_at', d)} DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()`,
  )
  out.push(`CREATE TABLE ${full(tn)} (`, cols.join(',\n'), ');')
  if (extras) {
    const links = table.fields.filter((f) => f.type === 'link')
    if (links.length) out.push('')
    for (const f of links)
      out.push(
        `CREATE INDEX ${quote(`${tn}_${columnName(f)}_idx`, d)} ON ${full(tn)} (${quote(columnName(f), d)});`,
      )
    if (d === 'postgres') {
      out.push('', `COMMENT ON TABLE ${full(tn)} IS ${sqlStr(table.name)};`)
      for (const f of table.fields)
        out.push(`COMMENT ON COLUMN ${full(tn)}.${quote(columnName(f), d)} IS ${sqlStr(f.name)};`)
    } else if (d === 'mysql') out.push('', `ALTER TABLE ${full(tn)} COMMENT = ${sqlStr(table.name)};`)
  }
  return out.join('\n')
}

const BSON: Partial<Record<TableFieldType, string>> = {
  auto_number: 'long',
  number: 'double',
  currency: 'decimal',
  date: 'date',
  datetime: 'date',
  checkbox: 'bool',
  multi_select: 'array',
  link: 'objectId',
  file: 'object',
  json: 'object',
}

export function generateMongoSchema(table: Table, ctx: DdlContext): string {
  const properties: Record<string, Record<string, unknown>> = { _id: { bsonType: 'objectId' } }
  for (const f of table.fields) {
    const p: Record<string, unknown> = { bsonType: BSON[f.type] ?? 'string', description: f.name }
    const allowed =
      f.type === 'single_select'
        ? f.options
        : f.type === 'workflow_state' && f.workflow
          ? ctx.workflowStates?.(f.workflow)
          : undefined
    if (allowed?.length) p.enum = allowed
    if (f.type === 'multi_select' && f.options?.length) p.items = { enum: f.options }
    properties[columnName(f)] = p
  }
  const schema = {
    bsonType: 'object',
    required: table.fields.filter((f) => f.req).map(columnName),
    properties,
  }
  const body = JSON.stringify({ validator: { $jsonSchema: schema } }, null, 2)
  const name = tableName(table)
  const out = [
    `// ${ctx.connection.name} · MongoDB`,
    `// Generated by Platon Studio from data.tables.${table.id}`,
    '',
    `db.createCollection(${JSON.stringify(name)}, ${body});`,
  ]
  if (ctx.extras) {
    const idx = table.fields.filter((f) => f.type === 'link' || f.unique)
    if (idx.length) out.push('')
    for (const f of idx)
      out.push(`db.${name}.createIndex({ ${columnName(f)}: 1 }${f.unique ? ', { unique: true }' : ''});`)
  }
  return out.join('\n')
}

/** "1 day" → 86400, "15 minutes" → 900; undefined for "No expiry" or unknown text. */
export function ttlSeconds(ttl: string | undefined): number | undefined {
  const m = /(\d+)\s*(s|sec|second|m|min|minute|h|hour|d|day|w|week)s?\b/i.exec(ttl ?? '')
  if (!m) return undefined
  const unit = m[2]!.toLowerCase()[0]!
  const mult = { s: 1, m: 60, h: 3600, d: 86400, w: 604800 }[unit as 's' | 'm' | 'h' | 'd' | 'w']
  return Number(m[1]) * mult
}

export function redisKeyPattern(table: Table, appSlug: string): string {
  return table.physicalName?.includes(':')
    ? table.physicalName
    : `${snake(appSlug) || 'app'}:${table.id}:{id}`
}

export function generateRedisSpec(table: Table, ctx: DdlContext, appSlug: string): string {
  const pattern = redisKeyPattern(table, appSlug)
  const secs = ttlSeconds(table.ttl)
  const sample = pattern.replace('{id}', 'a81f')
  const valueFields = table.fields.filter((f) => f.key !== 'key' && f.key !== 'ttl')
  const out = [
    `# ${ctx.connection.name} · Redis`,
    `# Key set:  ${table.name}`,
    `# Pattern:  ${pattern}`,
    `# Expires:  ${secs ? `${table.ttl} (${secs} s)` : 'never'}`,
    `# Fields:   ${valueFields.map((f) => columnName(f)).join(', ') || '—'}`,
    '',
    `HSET ${sample} ${valueFields.map((f) => `${columnName(f)} "…"`).join(' ') || 'value "…"'}`,
  ]
  if (secs) out.push(`EXPIRE ${sample} ${secs}`)
  return out.join('\n')
}

export interface DdlResult {
  text: string
  language: 'sql' | 'javascript' | 'plaintext'
  file: string
}

export function generateDdl(
  table: Table,
  ctx: DdlContext,
  opts: { dialect?: SqlDialect; appSlug?: string } = {},
): DdlResult {
  const e = ctx.connection.engine
  const name = tableName(table)
  if (isSqlEngine(e))
    return { text: generateSqlDdl(table, ctx, opts.dialect ?? e), language: 'sql', file: `${name}.sql` }
  if (e === 'mongo')
    return { text: generateMongoSchema(table, ctx), language: 'javascript', file: `${name}.js` }
  return {
    text: generateRedisSpec(table, ctx, opts.appSlug ?? 'app'),
    language: 'plaintext',
    file: `${table.id}.redis`,
  }
}
